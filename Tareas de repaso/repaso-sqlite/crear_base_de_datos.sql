-- Adaptacion SQLite de los modelos Producto y Vehiculo de CodeLearn Academy.
-- Los 200 registros INSERT son datos sinteticos didacticos, NO datos originales del sitio.
-- https://codelearnacademy.github.io/ficheros/leccion06/
-- https://codelearnacademy.github.io/ficheros/leccion30/
PRAGMA foreign_keys = ON;
CREATE TABLE Productos (
    id INTEGER PRIMARY KEY CHECK(id > 0),
    nombre TEXT NOT NULL CHECK(length(trim(nombre)) > 0),
    precio REAL NOT NULL CHECK(precio >= 0)
);
CREATE TABLE Vehiculos (
    matricula TEXT PRIMARY KEY NOT NULL CHECK(length(trim(matricula)) > 0 AND matricula = upper(trim(matricula))),
    marca TEXT NOT NULL CHECK(length(trim(marca)) > 0),
    modelo TEXT NOT NULL CHECK(length(trim(modelo)) > 0),
    anio INTEGER NOT NULL CHECK(anio >= 1886)
);

